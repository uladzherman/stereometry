'use strict';
/* 30-problems-variants.js — Задачи из вариантов (A15, A16, B8, B12, сечения куба). */
(function(){
  const T=PROBLEM_TOPICS;
  const push=(i,arr)=>{ if(T[i]) T[i].tasks.push.apply(T[i].tasks,arr); };
  const topic=(title)=>T.find(t=>t.title===title);

  const ptsOn=(list)=>list.map(m=>({label:m[0],a:m[1],b:m[2],r:m[3]}));

  /* A15: правильная треугольная призма, сечение через сторону основания и вершину C₁ */
  push(3,[
    { title:'A15: призма, сечение ABC₁ (a = 14)',
      text:'В правильной треугольной призме ABCA₁B₁C₁ сторона основания равна 14, а плоскость сечения проходит через сторону AB нижнего основания и противоположную вершину C₁ верхнего основания, образуя с плоскостью основания угол 30°. Найдите площадь сечения.',
      shape:'prism3', size:14, height:7,
      answer:['A','B','C₁'],
      hint:'Сечение — треугольник ABC₁. Его проекция на основание — треугольник ABC площадью a²√3/4. При угле 30° высота призмы равна a/2.',
      res:'S_сеч = S_осн / cos 30° = (a²√3/4)/(√3/2) = a²/2 = 98.' },
    { title:'A15: призма, сечение ABC₁ (a = 6)',
      text:'В правильной треугольной призме ABCA₁B₁C₁ сторона основания равна 6. Плоскость сечения проходит через сторону AB нижнего основания и вершину C₁ верхнего основания под углом 30° к основанию. Найдите площадь сечения.',
      shape:'prism3', size:6, height:3,
      answer:['A','B','C₁'],
      hint:'Та же формула: S = a²/2.',
      res:'S = a²/2 = 18.' }
  ]);

  /* A16: прямоугольный параллелепипед, наклонное сечение через середины AA₁ и BB₁ */
  const a16=(AB,AD,H,ans,no)=>(
    { title:'A16 (вариант '+no+'): наклонное сечение',
      text:'ABCDA₁B₁C₁D₁ — прямоугольный параллелепипед, AB = '+AB+', AD = '+AD+'. Через середины рёбер AA₁ и BB₁ проведена плоскость, составляющая угол 60° с плоскостью основания ABCD. Найдите площадь сечения.',
      shape:'box', height:H,
      base:[[-AB/2,-AD/2],[AB/2,-AD/2],[AB/2,AD/2],[-AB/2,AD/2]],
      mids:[{label:'M',a:'A',b:'A₁'},{label:'N',a:'B',b:'B₁'}],
      pts:[{label:'P',p:[-AB/2,0,AD*Math.sqrt(3)/2]}],
      answer:['M','N','P'],
      hint:'Проекция сечения на основание — прямоугольник ABCD площадью AB·AD. Площадь сечения равна проекции, делённой на cos 60°.',
      res:'S = AB·AD / cos 60° = '+ans+'.' });
  push(3,[
    a16(16,4,16,128,2),
    a16(16,2,8,64,3),
    a16(16,3,12,96,4)
  ]);

  /* A15 (куб): тип сечения по трём точкам, включая деление ребра */
  const cubeSec=(no,text,mids,ansVal,resText)=>(
    { title:'Куб: тип сечения (вариант '+no+')',
      text:'ABCDA₁B₁C₁D₁ — куб. '+text+' Каким является сечение куба плоскостью, проходящей через точки M, N и K?',
      shape:'cube', size:2,
      mids:mids, answer:['M','N','K'],
      hint:'Постройте точки на рёбрах по заданным отношениям и проследите, какие рёбра куба пересекает плоскость MNK.',
      res:resText });
  push(3,[
    cubeSec(1,'Точки M и N — середины рёбер AD и DC, K ∈ A₁D₁, KA₁ : KD₁ = 1 : 3.',
      ptsOn([['M','A','D',0.5],['N','D','C',0.5],['K','A₁','D₁',0.25]]),0,'Сечение — четырёхугольник.'),
    cubeSec(2,'Точки M и N — середины рёбер B₁C₁ и CC₁, K ∈ DD₁, KD : KD₁ = 1 : 2.',
      ptsOn([['M','B₁','C₁',0.5],['N','C','C₁',0.5],['K','D','D₁',1/3]]),0,'Сечение — четырёхугольник.'),
    cubeSec(3,'Точки M и N — середины рёбер AB и AD, K ∈ BB₁, KB₁ : KB = 1 : 3.',
      ptsOn([['M','A','B',0.5],['N','A','D',0.5],['K','B','B₁',0.75]]),0,'Сечение — шестиугольник.'),
    cubeSec(4,'Точки M и N — середины рёбер B₁C₁ и CC₁, K ∈ A₁D₁, KA₁ : KD₁ = 1 : 3.',
      ptsOn([['M','B₁','C₁',0.5],['N','C','C₁',0.5],['K','A₁','D₁',0.25]]),0,'Сечение — четырёхугольник.'),
    cubeSec(5,'Точки M и N — середины рёбер AB и AD, K ∈ A₁D₁, KD₁ : KA₁ = 1 : 2.',
      ptsOn([['M','A','B',0.5],['N','A','D',0.5],['K','A₁','D₁',2/3]]),0,'Сечение — четырёхугольник.')
  ]);

  /* ЦТ B12: сечение делит параллелепипед на части (отношения на рёбрах) */
  const P=topic('Площади и объёмы');
  if(P) P.tasks.push(
    { title:'ЦТ B12 (вар. 1): меньшая часть',
      text:'Объём прямоугольного параллелепипеда ABCDA₁B₁C₁D₁ равен 1728. Точка P лежит на ребре CC₁ так, что CP : PC₁ = 2 : 1. Через точку P, вершину D и середину ребра AA₁ проведена секущая плоскость, делящая параллелепипед на две части. Найдите объём меньшей из частей.',
      shape:'cube', size:12,
      mids:[{label:'Q',a:'A',b:'A₁',r:0.5},{label:'P',a:'C',b:'C₁',r:2/3}],
      construct:[{t:'plane',a:'D',b:'P',c:'Q'}],
      hint:'Отношения объёмов частей не зависят от формы параллелепипеда (аффинное преобразование куба).',
      res:'Объём меньшей части равен 724.' },
    { title:'ЦТ B12 (вар. 2): большая часть',
      text:'Объём прямоугольного параллелепипеда ABCDA₁B₁C₁D₁ равен 1728. Точка K лежит на ребре BB₁ так, что BK : KB₁ = 2 : 1. Через точку K, вершину C и середину ребра DD₁ проведена секущая плоскость. Найдите объём большей из частей.',
      shape:'cube', size:12,
      mids:[{label:'Q',a:'D',b:'D₁',r:0.5},{label:'K',a:'B',b:'B₁',r:2/3}],
      construct:[{t:'plane',a:'C',b:'K',c:'Q'}],
      hint:'Объём большей части = объём минус меньшая.',
      res:'Объём большей части равен 1004.' },
    { title:'ЦТ B12 (вар. 3): меньшая часть',
      text:'Объём прямоугольного параллелепипеда ABCDA₁B₁C₁D₁ равен 432. Точка M лежит на ребре AA₁ так, что AM : MA₁ = 2 : 1. Через точку M, вершину B и середину ребра CC₁ проведена секущая плоскость. Найдите объём меньшей из частей.',
      shape:'cube', size:Math.cbrt(432),
      mids:[{label:'M',a:'A',b:'A₁',r:2/3},{label:'Q',a:'C',b:'C₁',r:0.5}],
      construct:[{t:'plane',a:'M',b:'B',c:'Q'}],
      hint:'Отношения объёмов частей не зависят от размеров параллелепипеда.',
      res:'Объём меньшей части равен 181.' },
    { title:'B8: призма с трапецией в основании',
      text:'В основании прямой четырёхугольной призмы ABCDA₁B₁C₁D₁ лежит трапеция ABCD, у которой ∠C = 90°, BC и AD — основания, BC = CC₁. Плоскость, проходящая через ребро DC и вершину A₁, образует угол α = arctg(5/3) с плоскостью основания и отсекает часть NC₁CA₁D₁D. Объём призмы равен 48. Найдите объём оставшейся части.',
      shape:'box',
      hint:'Отсечённая часть — пирамида/клин; свяжите объёмы через отношение площадей и высоту.',
      res:'Объём оставшейся части равен 30.' }
  );

  /* Диаграммы для формульных задач «Площади и объёмы» (показываются сразу) */
  const PA=topic('Площади и объёмы');
  const rr=x=>Math.round(x*1000)/1000;
  const SZ=t=>(t.size||2), HT=t=>(t.height||2);
  const great=t=>{ if(!t) return; const r=SZ(t)/2;
    t.pts=[{label:'O',p:[0,0,0]},{label:'A',p:[r,0,0]},{label:'B',p:[0,r,0]},{label:'C',p:[-r,0,0]}];
    t.construct=[{t:'plane',a:'A',b:'B',c:'C'},{t:'seg',a:'O',b:'A'}]; t.always=true; };
  const sphereSec=(dF,rF)=>t=>{ if(!t) return; const r=SZ(t)/2, z=rr(r*dF), q=rr(r*rF);
    t.pts=[{label:'O',p:[0,0,0]},{label:'A',p:[q,0,z]},{label:'B',p:[0,q,z]},{label:'C',p:[-q,0,z]}];
    t.construct=[{t:'plane',a:'A',b:'B',c:'C'},{t:'seg',a:'O',b:'A'}]; t.always=true; };
  const tangent=t=>{ if(!t) return; const r=SZ(t)/2;
    t.pts=[{label:'A',p:[r,0,r]},{label:'B',p:[0,r,r]},{label:'C',p:[-r,0,r]}];
    t.construct=[{t:'plane',a:'A',b:'B',c:'C'}]; t.always=true; };
  const cylAx=t=>{ if(!t) return; const r=SZ(t)/2,h=HT(t);
    t.pts=[{label:'A',p:[r,0,-h/2]},{label:'B',p:[r,0,h/2]},{label:'C',p:[-r,0,h/2]}];
    t.construct=[{t:'plane',a:'A',b:'B',c:'C'}]; t.always=true; };
  const coneAx=t=>{ if(!t) return; const r=SZ(t)/2,h=HT(t);
    t.pts=[{label:'S',p:[0,0,h/2]},{label:'A',p:[r,0,-h/2]},{label:'B',p:[-r,0,-h/2]}];
    t.construct=[{t:'plane',a:'S',b:'A',c:'B'}]; t.always=true; };
  const patch=(title,fn)=>{ const t=PA&&PA.tasks.find(x=>x.title===title); if(t) fn(t); };

  ['Цилиндр: боковая поверхность через осевое сечение','Цилиндр: высота через S и V','Цилиндр из вращения квадрата','Цилиндр и конус с общими основанием и высотой']
    .forEach(n=>patch(n,cylAx));
  ['Конус: боковая поверхность через образующую и высоту','Конус: образующая и угол наклона','Конус: площадь основания через объём','Изменение объёма конуса']
    .forEach(n=>patch(n,coneAx));
  ['Шар: площадь большого круга','Шар: поверхность по большому кругу','Шар, вписанный в цилиндр','Сфера: правильный треугольник на большом круге']
    .forEach(n=>patch(n,great));
  patch('Сфера: сечение на расстоянии от центра',sphereSec(0.8,0.6));
  patch('Сфера: сечение радиуса 2',sphereSec(0.894,0.447));
  patch('Сфера: касательная плоскость',tangent);
  patch('Сфера, описанная около конуса',t=>{ t.height=2; t.size=4; const r=2,h=2;
    t.pts=[{label:'O',p:[0,0,-h/2]},{label:'B',p:[r,0,-h/2]},{label:'S',p:[0,0,h/2]}];
    t.construct=[{t:'seg',a:'O',b:'S'},{t:'seg',a:'O',b:'B'}]; t.always=true; });
  patch('Цилиндр, вписанный в призму',t=>{ t.pts=[{label:'O',p:[0,0,0]},{label:'A',p:[5,0,0]}];
    t.construct=[{t:'seg',a:'O',b:'A'}]; t.always=true; });
  patch('Отсечённая пирамида',t=>{ t.mids=[{label:'M',a:'A',b:'B'},{label:'N',a:'A',b:'C'}];
    t.answer=['S','M','N']; t.always=true; });
  patch('Отсечённая призма (объём)',t=>{ t.mids=[{label:'M',a:'A',b:'B'},{label:'N',a:'A',b:'C'},{label:'P',a:'A₁',b:'B₁'}];
    t.answer=['M','N','P']; t.always=true; });
})();
